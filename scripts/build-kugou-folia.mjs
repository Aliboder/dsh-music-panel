#!/usr/bin/env node
/**
 * Bundle the ported Folia KuGou source for the Host.
 *
 * The upstream module (`sources/kugou/`) is TypeScript and stays that way in the mirror;
 * this script compiles it, with the plugin's host surfaces (`src/folia-adapters/kugou/`),
 * into one ESM file the Host loads. Nothing of the module's logic is rewritten here:
 * the only substitutions are the host APIs the desktop gave it.
 *
 *   node scripts/build-kugou-folia.mjs          # rebuild the bundle
 *   node scripts/build-kugou-folia.mjs --check  # fail when the committed bundle is stale
 *
 * @module dsh-music-panel/build-kugou-folia
 */
import { build } from 'esbuild'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'src/host/vendor/kugou-folia/source.bundle.mjs')
const KIT_INDEX = join(ROOT, 'src/folia-mods/packages/folium-source-kit/src/index.ts')
const HEADER = [
  '// Generated by scripts/build-kugou-folia.mjs - do not edit by hand.',
  '// Sources: A_other/upstream/folia-major-main/sources/kugou, mirrored verbatim to src/folia-mods/sources/kugou,',
  '// compiled together with the plugin-side host surfaces in src/folia-adapters/kugou/.',
  '',
].join('\n')

/** `@folia/folium-source-kit` is a Folia workspace package; here it is the mirrored copy. */
const foliumAliases = {
  name: 'folia-package-aliases',
  setup(context) {
    context.onResolve({ filter: /^@folia\/folium-source-kit$/ }, () => ({ path: KIT_INDEX }))
    // `await import('kugoumusicapi')` in the upstream main entry stays a runtime load, pointed at the package
    // this plugin already ships (v1.6.0, identical to upstream's): ../kugoumusicapi from src/host/vendor/kugou-folia/.
    context.onResolve({ filter: /^kugoumusicapi(\/.*)?$/ }, (args) => ({
      path: args.path === 'kugoumusicapi'
        ? '../kugoumusicapi/main.js'
        : '../kugoumusicapi' + args.path.slice('kugoumusicapi'.length),
      external: true,
    }))
  },
}

const bundle = async () => {
  const result = await build({
    entryPoints: [join(ROOT, 'src/folia-build/kugou-host-entry.ts')],
    write: false,
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: ['node20'],
    minify: false,
    sourcemap: false,
    logLevel: 'silent',
    legalComments: 'none',
    loader: { '.ts': 'ts', '.json': 'json' },
    banner: { js: 'import { createRequire as __mpCreateRequire } from "node:module"; const require = __mpCreateRequire(import.meta.url);' },
    plugins: [foliumAliases],
  })
  return HEADER + result.outputFiles[0].text.replace(/\r\n/g, '\n')
}

const checkOnly = process.argv.includes('--check')

try {
  const text = await bundle()
  if (checkOnly) {
    let current = ''
    try {
      current = readFileSync(OUT, 'utf8')
    } catch {
      current = ''
    }
    if (current !== text) {
      console.log('KUGOU FOLIA BUNDLE STALE')
      console.log('run: node scripts/build-kugou-folia.mjs')
      process.exitCode = 1
    } else {
      console.log('KUGOU FOLIA BUNDLE OK ' + text.length + ' bytes')
    }
  } else {
    mkdirSync(dirname(OUT), { recursive: true })
    writeFileSync(OUT, text, 'utf8')
    console.log('KUGOU FOLIA BUNDLE OK bytes=' + text.length)
  }
} catch (error) {
  const errors = error.errors || []
  console.log('ERRORS ' + errors.length)
  console.log(errors.slice(0, 30).map(item => (item.location ? item.location.file.split('folia-mods/').pop() + ':' + item.location.line + ' ' : '') + item.text).join('\n'))
  process.exitCode = 1
}
